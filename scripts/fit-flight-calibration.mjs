#!/usr/bin/env node
/**
 * Fit and validate the flat-disk radial scale against the collected ADS-B
 * flight telemetry dataset. Target distances are ground-speed × elapsed-time
 * integrations, never coordinate-derived route lengths.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fitFlightCalibration } from '../src/core/flight-calibration-fit.js';

const DATA_PATH = 'data/flight-calibration.json';
const PARAMETERS_PATH = 'src/core/flight-calibration-parameters.js';
const SUMMARY_PATH = 'data/flight-calibration-summary.json';

function asJavaScript(model) {
  return [
    '/** Generated by scripts/fit-flight-calibration.mjs. Do not edit by hand. */',
    'export const FLIGHT_CALIBRATION = Object.freeze(' + JSON.stringify(model, null, 2) + ');',
    ''
  ].join('\n');
}

async function main() {
  let dataset;
  try {
    dataset = JSON.parse(await readFile(DATA_PATH, 'utf8'));
  } catch (error) {
    throw new Error('Could not read ' + DATA_PATH + ': ' + error.message);
  }

  let fitted;
  try {
    fitted = fitFlightCalibration(dataset);
  } catch (error) {
    if (String(error.message).includes('Insufficient empirical route coverage')) {
      console.warn(error.message);
      console.warn('No production coefficients were written; keep collecting flight telemetry.');
      return;
    }
    throw error;
  }

  const summary = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    sourceDataset: DATA_PATH,
    sourceRetrievedAt: dataset.source && dataset.source.retrievedAt,
    method: {
      target: 'Median observed flown-path length per airport pair',
      targetSource: 'ADS-B ground-speed telemetry integrated over timestamps',
      formula: 'sum(ground_speed_knots * elapsed_seconds / 3600) * 1.852',
      inputGeometry: 'Flat radial disk chord with R=1, followed by empirical radial scale and a three-feature ridge residual fit',
      features: fitted.model.featureNames,
      trainingUnit: 'one independent airport pair, target is median of >=3 observed flights',
      splitUnit: 'entire airport pairs held out; no flight from a holdout route is fitted'
    },
    model: fitted.model,
    metrics: fitted.metrics,
    routeCoverage: {
      trainingRoutes: fitted.model.trainingRouteCount,
      holdoutRoutes: fitted.model.holdoutRouteCount,
      totalRoutes: (dataset.routes || []).filter(route => route.sampleCount >= 3).length
    }
  };

  await writeFile(PARAMETERS_PATH, asJavaScript(fitted.model), 'utf8');
  await writeFile(SUMMARY_PATH, JSON.stringify(summary, null, 2) + '\n', 'utf8');

  console.log('FLIGHT_CALIBRATION_FIT_BEGIN');
  console.log(JSON.stringify(summary, null, 2));
  console.log('FLIGHT_CALIBRATION_FIT_END');
  console.log('Wrote ' + PARAMETERS_PATH + ' and ' + SUMMARY_PATH);
}

main().catch(error => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
