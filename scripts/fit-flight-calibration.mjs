#!/usr/bin/env node
/**
 * Fit and validate the flat-disk radial scale against the collected ADS-B
 * flight telemetry dataset. Target distances are ground-speed × elapsed-time
 * integrations, never coordinate-derived route lengths.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fitFlightCalibration, summarizeFlightCalibrationCoverage } from '../src/core/flight-calibration-fit.js';

const DATA_PATH = 'data/flight-calibration.json';
const PARAMETERS_PATH = 'src/core/flight-calibration-parameters.js';
const SUMMARY_PATH = 'data/flight-calibration-summary.json';
const MAX_TRAINING_MAPE = 10;
const MAX_HOLDOUT_MAPE = 12;
const MAX_HOLDOUT_ROUTE_ERROR = 20;
const MAX_LEAVE_ONE_OUT_MAPE = 15;
const MAX_LEAVE_ONE_OUT_ROUTE_ERROR = 45;
const MIN_TRAINING_ROUTES = 20;
const MIN_HOLDOUT_ROUTES = 6;
const MIN_SOUTHERN_TRAINING_ROUTES = 4;
const MIN_SOUTHERN_HOLDOUT_ROUTES = 2;

function asJavaScript(model) {
  return [
    '/** Generated by scripts/fit-flight-calibration.mjs. Do not edit by hand. */',
    'export const FLIGHT_CALIBRATION = Object.freeze(' + JSON.stringify(model, null, 2) + ');',
    ''
  ].join('\n');
}

async function main() {
  let dataset;
  try {
    dataset = JSON.parse(await readFile(DATA_PATH, 'utf8'));
  } catch (error) {
    throw new Error('Could not read ' + DATA_PATH + ': ' + error.message);
  }

  let fitted;
  try {
    fitted = fitFlightCalibration(dataset);
  } catch (error) {
    if (String(error.message).includes('Insufficient empirical route coverage')) {
      const spatialCoverage = summarizeFlightCalibrationCoverage(dataset);
      const southernCandidates = (dataset.routes || []).filter(route =>
        Number.isFinite(route.airportA?.lat) &&
        Number.isFinite(route.airportB?.lat) &&
        Math.min(route.airportA.lat, route.airportB.lat) <= -45
      ).map(route => ({
        routeId: route.routeId,
        split: route.split,
        airportA: route.airportA?.ident || null,
        airportB: route.airportB?.ident || null,
        minEndpointLatitude: Math.min(route.airportA.lat, route.airportB.lat),
        candidateFlightsSeen: route.candidatesSeen || 0,
        pagesScanned: route.pagesScanned || 0,
        acceptedFlights: route.sampleCount || 0
      }));
      const rejectedSummary = {
        schemaVersion: 1,
        accepted: false,
        status: 'insufficient-route-coverage',
        generatedAt: new Date().toISOString(),
        sourceDataset: DATA_PATH,
        sourceRetrievedAt: dataset.source && dataset.source.retrievedAt,
        rejectionReason: error.message,
        qualityGate: {
          ...spatialCoverage,
          limits: {
            minimumTrainingRoutes: MIN_TRAINING_ROUTES,
            minimumHoldoutRoutes: MIN_HOLDOUT_ROUTES,
            minimumSouthernTrainingRoutes: MIN_SOUTHERN_TRAINING_ROUTES,
            minimumSouthernHoldoutRoutes: MIN_SOUTHERN_HOLDOUT_ROUTES
          }
        },
        model: null,
        metrics: null,
        routeCoverage: {
          ...spatialCoverage,
          candidateRoutes: (dataset.routes || []).length,
          totalObservedFlights: (dataset.routes || []).reduce(
            (sum, route) => sum + (route.sampleCount || 0), 0
          ),
          routesWithAtLeastThreeFlights: (dataset.routes || []).filter(
            route => (route.sampleCount || 0) >= 3
          ).length,
          southernRouteCandidates: southernCandidates
        }
      };
      await writeFile(SUMMARY_PATH, JSON.stringify(rejectedSummary, null, 2) + '\n', 'utf8');
      console.warn(error.message);
      console.warn('Candidate summary recorded as rejected; production coefficients were preserved.');
      return;
    }
    throw error;
  }

  const qualityGate = {
    trainingMapePercent: fitted.metrics.training.meanAbsolutePercent,
    holdoutMapePercent: fitted.metrics.holdout.meanAbsolutePercent,
    holdoutMaxErrorPercent: fitted.metrics.holdout.maxAbsolutePercent,
    leaveOneOutMapePercent: fitted.metrics.leaveOneOut?.meanAbsolutePercent ?? null,
    leaveOneOutMaxRouteErrorPercent: fitted.metrics.leaveOneOut?.maxAbsolutePercent ?? null,
    trainingRouteCount: fitted.metrics.spatialCoverage.trainingRouteCount,
    holdoutRouteCount: fitted.metrics.spatialCoverage.holdoutRouteCount,
    trainingRoutesSouthOf30S: fitted.metrics.spatialCoverage.trainingRoutesSouthOf30S,
    trainingRoutesSouthOf45S: fitted.metrics.spatialCoverage.trainingRoutesSouthOf45S,
    trainingRoutesSouthOf60S: fitted.metrics.spatialCoverage.trainingRoutesSouthOf60S,
    holdoutRoutesSouthOf30S: fitted.metrics.spatialCoverage.holdoutRoutesSouthOf30S,
    holdoutRoutesSouthOf45S: fitted.metrics.spatialCoverage.holdoutRoutesSouthOf45S,
    holdoutRoutesSouthOf60S: fitted.metrics.spatialCoverage.holdoutRoutesSouthOf60S,
    limits: {
      minimumTrainingRoutes: MIN_TRAINING_ROUTES,
      minimumHoldoutRoutes: MIN_HOLDOUT_ROUTES,
      minimumSouthernTrainingRoutes: MIN_SOUTHERN_TRAINING_ROUTES,
      minimumSouthernHoldoutRoutes: MIN_SOUTHERN_HOLDOUT_ROUTES,
      maxTrainingMapePercent: MAX_TRAINING_MAPE,
      maxHoldoutMapePercent: MAX_HOLDOUT_MAPE,
      maxHoldoutRouteErrorPercent: MAX_HOLDOUT_ROUTE_ERROR,
      maxLeaveOneOutMapePercent: MAX_LEAVE_ONE_OUT_MAPE,
      maxLeaveOneOutRouteErrorPercent: MAX_LEAVE_ONE_OUT_ROUTE_ERROR
    }
  };
  const accepted =
    qualityGate.trainingMapePercent <= MAX_TRAINING_MAPE &&
    qualityGate.holdoutMapePercent <= MAX_HOLDOUT_MAPE &&
    qualityGate.holdoutMaxErrorPercent <= MAX_HOLDOUT_ROUTE_ERROR &&
    Number.isFinite(qualityGate.leaveOneOutMapePercent) &&
    qualityGate.leaveOneOutMapePercent <= MAX_LEAVE_ONE_OUT_MAPE &&
    qualityGate.leaveOneOutMaxRouteErrorPercent <= MAX_LEAVE_ONE_OUT_ROUTE_ERROR &&
    qualityGate.trainingRouteCount >= MIN_TRAINING_ROUTES &&
    qualityGate.holdoutRouteCount >= MIN_HOLDOUT_ROUTES &&
    qualityGate.trainingRoutesSouthOf30S >= MIN_SOUTHERN_TRAINING_ROUTES &&
    qualityGate.holdoutRoutesSouthOf30S >= MIN_SOUTHERN_HOLDOUT_ROUTES;

  const summary = {
    schemaVersion: 1,
    accepted,
    qualityGate,
    generatedAt: new Date().toISOString(),
    sourceDataset: DATA_PATH,
    sourceRetrievedAt: dataset.source && dataset.source.retrievedAt,
    method: {
      target: 'Median directly observed flown mileage per airport pair',
      targetSource: 'ADS-B path_gs ground-speed/time observations with at least 98% full-flight coverage and no gap over 15 minutes',
      formula: 'observed_km = sum(speed_knots * delta_seconds / 3600) * 1.852; no missing interval is imputed',
      inputGeometry: 'Circular flat disk with regularized-power latitude warp q(t); local inverse-distance-weighted mileage-per-warped-chord ratios over mean warped radial fraction and normalized radial/tangential chord shares',
      radialWarp: fitted.model.radialWarp,
      radialCoordinateFormula: 't = theta / pi; q = ((t + epsilon)^exponent - epsilon^exponent) / ((1 + epsilon)^exponent - epsilon^exponent); r = pi * R * q',
      features: fitted.model.featureNames,
      trainingUnit: 'one independent airport pair, target is median of >=3 high-coverage observed flights',
      splitUnit: 'entire airport pairs held out; no flight from a holdout route is fitted',
      coverageDenominator: 'full-flight-duration',
      distancePolicy: 'observed-only'
    },
    model: fitted.model,
    metrics: fitted.metrics,
    routeCoverage: {
      ...fitted.metrics.spatialCoverage,
      candidateRoutes: (dataset.routes || []).length,
      totalObservedFlights: (dataset.routes || []).reduce(
        (sum, route) => sum + (route.sampleCount || 0), 0
      ),
      totalRoutes: (dataset.routes || []).filter(route => route.sampleCount >= 3).length
    }
  };

  await writeFile(SUMMARY_PATH, JSON.stringify(summary, null, 2) + '\n', 'utf8');

  if (!accepted) {
    // Keep the last approved production model. A rejected candidate must never
    // remove or overwrite a working calibration used by the live map.
    console.warn('Calibration candidate rejected by the independent validation gate.');
    console.warn('The last approved production parameters were preserved. Improve route coverage or telemetry quality.');
  } else {
    await writeFile(PARAMETERS_PATH, asJavaScript(fitted.model), 'utf8');
    console.log('Accepted calibration parameters written to ' + PARAMETERS_PATH);
  }

  console.log('FLIGHT_CALIBRATION_FIT_BEGIN');
  console.log(JSON.stringify(summary, null, 2));
  console.log('FLIGHT_CALIBRATION_FIT_END');
  console.log('Wrote ' + SUMMARY_PATH);
}

main().catch(error => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
