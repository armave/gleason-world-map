#!/usr/bin/env node
/**
 * Fit a local endpoint-mileage estimate from observed-only ADS-B route records.
 * The exact projection chord is derived from the active flat-disk map; no
 * globe-derived distance or route-length formula is used.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { endpointDistanceFeatures } from '../src/core/endpoint-distance-calibration.js';

const DATA_PATH = 'data/flight-calibration.json';
const PARAMETERS_PATH = 'src/core/endpoint-distance-calibration-parameters.js';
const SUMMARY_PATH = 'data/endpoint-distance-calibration-summary.json';
const MAX_TRAINING_SPREAD_FRACTION = 0.60;
const MAX_SUPPORTED_FEATURE_DISTANCE = 0.90;
const NEIGHBOR_COUNT = 4;
const INVERSE_DISTANCE_POWER = 1;
const FACTOR_BOUNDS = [0.75, 1.5];

function validRoute(route) {
  return route && Number.isFinite(route.medianTrackKm) && route.medianTrackKm > 0 &&
    Number.isFinite(route.sampleCount) && route.sampleCount >= 3 &&
    Number.isFinite(route.p10TrackKm) && Number.isFinite(route.p90TrackKm) &&
    route.airportA && route.airportB;
}

function routeExample(route) {
  if (!validRoute(route)) return null;
  const geometry = endpointDistanceFeatures(route.airportA, route.airportB);
  if (!geometry || !(geometry.chordDistanceMeters > 0)) return null;
  const chordKm = geometry.chordDistanceMeters / 1000;
  const spreadFraction = (route.p90TrackKm - route.p10TrackKm) /
    route.medianTrackKm;
  return {
    routeId: route.routeId,
    split: route.split,
    features: geometry.features,
    chordKm,
    medianTrackKm: route.medianTrackKm,
    mileagePerUnitChord: route.medianTrackKm / chordKm,
    sampleCount: route.sampleCount,
    spreadFraction
  };
}

function statistics(routes) {
  const featureMeans = [0, 1, 2, 3].map(index =>
    routes.reduce((sum, route) => sum + route.features[index], 0) / routes.length
  );
  const featureScales = [0, 1, 2].map(index => {
    const variance = routes.reduce(
      (sum, route) => sum + (route.features[index] - featureMeans[index]) ** 2,
      0
    ) / routes.length;
    return Math.sqrt(variance) || 1;
  });
  return { featureMeans, featureScales };
}

function nearestPrediction(query, training, modelStatistics) {
  const neighbors = training.map(route => {
    const distance = Math.sqrt(query.features.reduce((sum, value, index) =>
      sum + ((value - route.features[index]) / modelStatistics.featureScales[index]) ** 2,
    0));
    return { route, distance };
  }).sort((a, b) => a.distance - b.distance).slice(0, NEIGHBOR_COUNT);

  const weights = neighbors.map(neighbor =>
    1 / Math.pow(Math.max(0.025, neighbor.distance), INVERSE_DISTANCE_POWER)
  );
  const totalWeight = weights.reduce((sum, weight) => sum + weight, 0);
  const mileagePerUnitChord = Math.exp(neighbors.reduce(
    (sum, neighbor, index) =>
      sum + weights[index] * Math.log(neighbor.route.mileagePerUnitChord),
    0
  ) / totalWeight);

  return {
    mileagePerUnitChord,
    nearestFeatureDistance: neighbors[0]?.distance ?? Infinity,
    neighborRouteIds: neighbors.map(neighbor => neighbor.route.routeId),
    neighborWeights: weights.map(weight => weight / totalWeight)
  };
}

function summarize(predictions) {
  const supported = predictions.filter(item =>
    item.prediction.nearestFeatureDistance <= MAX_SUPPORTED_FEATURE_DISTANCE
  );
  const errors = supported.map(item =>
    (item.prediction.mileagePerUnitChord / item.route.mileagePerUnitChord - 1) * 100
  );
  return {
    routeCount: predictions.length,
    supportedRouteCount: supported.length,
    supportedCoveragePercent: predictions.length
      ? supported.length / predictions.length * 100 : 0,
    meanAbsolutePercent: errors.length
      ? errors.reduce((sum, error) => sum + Math.abs(error), 0) / errors.length
      : null,
    maxAbsolutePercent: errors.length
      ? Math.max(...errors.map(Math.abs)) : null,
    supportedRouteErrors: supported.map((item, index) => ({
      routeId: item.route.routeId,
      errorPercent: errors[index],
      nearestFeatureDistance: item.prediction.nearestFeatureDistance
    })),
    unsupportedRoutes: predictions.filter(item =>
      item.prediction.nearestFeatureDistance > MAX_SUPPORTED_FEATURE_DISTANCE
    ).map(item => ({
      routeId: item.route.routeId,
      nearestFeatureDistance: item.prediction.nearestFeatureDistance
    }))
  };
}

function asJavaScript(model) {
  return [
    '/** Generated by scripts/fit-endpoint-distance-calibration.mjs. Do not edit by hand. */',
    'export const ENDPOINT_DISTANCE_CALIBRATION = Object.freeze(' +
      JSON.stringify(model, null, 2) + ');',
    ''
  ].join('\n');
}

async function main() {
  const dataset = JSON.parse(await readFile(DATA_PATH, 'utf8'));
  const examples = (dataset.routes || []).map(routeExample).filter(Boolean);
  const training = examples.filter(route =>
    route.split === 'train' &&
    Number.isFinite(route.spreadFraction) &&
    route.spreadFraction <= MAX_TRAINING_SPREAD_FRACTION
  );
  const holdout = examples.filter(route => route.split === 'holdout');
  if (training.length < 20 || holdout.length < 6) {
    throw new Error(
      'Insufficient usable endpoint routes: need at least 20 training and 6 holdout; got ' +
      training.length + ' and ' + holdout.length + '.'
    );
  }

  const fullStatistics = statistics(training);
  const trainingLeaveOneRouteOut = summarize(training.map(route => {
    const foldTraining = training.filter(item => item.routeId !== route.routeId);
    return {
      route,
      prediction: nearestPrediction(route, foldTraining, statistics(foldTraining))
    };
  }));
  const independentHoldout = summarize(holdout.map(route => ({
    route,
    prediction: nearestPrediction(route, training, fullStatistics)
  })));

  const qualityGate = {
    trainingRouteCount: training.length,
    holdoutRouteCount: holdout.length,
    trainingSupportedLeaveOneOutRouteCount:
      trainingLeaveOneRouteOut.supportedRouteCount,
    holdoutSupportedRouteCount: independentHoldout.supportedRouteCount,
    trainingLeaveOneRouteOutMapePercent:
      trainingLeaveOneRouteOut.meanAbsolutePercent,
    trainingLeaveOneRouteOutMaxErrorPercent:
      trainingLeaveOneRouteOut.maxAbsolutePercent,
    holdoutMapePercent: independentHoldout.meanAbsolutePercent,
    holdoutMaxErrorPercent: independentHoldout.maxAbsolutePercent,
    limits: {
      minimumTrainingRoutes: 20,
      minimumHoldoutRoutes: 6,
      minimumSupportedTrainingLeaveOneOutRoutes: 20,
      minimumSupportedHoldoutRoutes: 4,
      maximumTrainingLeaveOneRouteOutMapePercent: 15,
      maximumTrainingLeaveOneRouteOutMaxErrorPercent: 20,
      maximumHoldoutMapePercent: 12,
      maximumHoldoutMaxErrorPercent: 20
    }
  };

  const accepted =
    qualityGate.trainingRouteCount >= qualityGate.limits.minimumTrainingRoutes &&
    qualityGate.holdoutRouteCount >= qualityGate.limits.minimumHoldoutRoutes &&
    qualityGate.trainingSupportedLeaveOneOutRouteCount >=
      qualityGate.limits.minimumSupportedTrainingLeaveOneOutRoutes &&
    qualityGate.holdoutSupportedRouteCount >=
      qualityGate.limits.minimumSupportedHoldoutRoutes &&
    qualityGate.trainingLeaveOneRouteOutMapePercent <=
      qualityGate.limits.maximumTrainingLeaveOneRouteOutMapePercent &&
    qualityGate.trainingLeaveOneRouteOutMaxErrorPercent <=
      qualityGate.limits.maximumTrainingLeaveOneRouteOutMaxErrorPercent &&
    qualityGate.holdoutMapePercent <= qualityGate.limits.maximumHoldoutMapePercent &&
    qualityGate.holdoutMaxErrorPercent <= qualityGate.limits.maximumHoldoutMaxErrorPercent;

  const model = {
    schemaVersion: 1,
    sourceDatasetVersion: dataset.schemaVersion,
    target: 'Median observed ADS-B ground-speed/time mileage by airport pair',
    geometry: 'Current displayed 12-circle radial and anchored longitude-warped flat disk',
    featureNames: ['meanRadialFraction', 'radialShareOfChord', 'tangentialShareOfChord', 'logChordDistanceKm'],
    featureMeans: fullStatistics.featureMeans,
    featureScales: fullStatistics.featureScales,
    neighborCount: NEIGHBOR_COUNT,
    inverseDistancePower: INVERSE_DISTANCE_POWER,
    maxTrainingSpreadFraction: MAX_TRAINING_SPREAD_FRACTION,
    maxSupportedFeatureDistance: MAX_SUPPORTED_FEATURE_DISTANCE,
    factorBounds: FACTOR_BOUNDS,
    trainingRouteCount: training.length,
    holdoutRouteCount: holdout.length,
    trainingExamples: training.map(route => ({
      routeId: route.routeId,
      features: route.features,
      medianTrackKm: route.medianTrackKm,
      mileagePerUnitChord: route.mileagePerUnitChord,
      sampleCount: route.sampleCount,
      spreadFraction: route.spreadFraction
    })),
    validation: { trainingLeaveOneRouteOut, independentHoldout }
  };

  const summary = {
    schemaVersion: 1,
    accepted,
    generatedAt: new Date().toISOString(),
    sourceDataset: DATA_PATH,
    sourceRetrievedAt: dataset.source?.retrievedAt ?? null,
    method: {
      target: model.target,
      endpointGeometry: model.geometry,
      predictor: 'four nearest route examples in standardized four-feature space; inverse-distance weighted geometric mean of observed mileage-per-chord ratios',
      featureNames: model.featureNames,
      routeQualityFilter: 'at least 3 accepted flights and (p90TrackKm - p10TrackKm) / medianTrackKm <= 0.60',
      supportRule: 'nearest standardized feature distance <= 0.65',
      factorBounds: FACTOR_BOUNDS
    },
    qualityGate,
    excludedTrainingRoutes: examples.filter(route =>
      route.split === 'train' && route.spreadFraction > MAX_TRAINING_SPREAD_FRACTION
    ).map(route => ({
      routeId: route.routeId,
      spreadFraction: route.spreadFraction,
      medianTrackKm: route.medianTrackKm,
      sampleCount: route.sampleCount
    })),
    metrics: { trainingLeaveOneRouteOut, independentHoldout },
    supportedDomainOnly: true
  };

  await writeFile(SUMMARY_PATH, JSON.stringify(summary, null, 2) + '\n', 'utf8');
  if (accepted) {
    await writeFile(PARAMETERS_PATH, asJavaScript(model), 'utf8');
    console.log('Accepted endpoint-distance calibration written to ' + PARAMETERS_PATH);
  } else {
    console.warn('Endpoint-distance calibration rejected; previous production parameters preserved.');
  }
  console.log(JSON.stringify(summary, null, 2));
}

main().catch(error => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
