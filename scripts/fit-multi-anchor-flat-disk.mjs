#!/usr/bin/env node
/**
 * Fit an experimental multi-anchor flat-disk candidate.
 * Input records must be independently measured endpoint-to-endpoint straight
 * distances. Flight mileage is explicitly ineligible. Production files are
 * never changed by this script.
 */
import { readFile, writeFile } from 'node:fs/promises';
import {
  fitMultiAnchorFlatDisk,
  summarizeMultiAnchorCoverage
} from '../src/core/multi-anchor-flat-disk.js';

const INPUT_PATH = 'data/multi-anchor-distance-observations.json';
const SUMMARY_PATH = 'data/multi-anchor-distance-calibration-summary.json';
const PARAMETERS_PATH = 'src/core/multi-anchor-flat-disk-parameters.js';

async function main() {
  const input = JSON.parse(await readFile(INPUT_PATH, 'utf8'));
  const observations = Array.isArray(input) ? input : input.observations;
  const fit = fitMultiAnchorFlatDisk(observations);
  const summary = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    sourceDataset: INPUT_PATH,
    sourceDatasetVersion: input.schemaVersion ?? null,
    measurementPolicy: input.measurementPolicy ?? null,
    accepted: fit.accepted,
    status: fit.status,
    failures: fit.failures,
    coverage: fit.coverage || summarizeMultiAnchorCoverage(observations),
    metrics: fit.metrics,
    candidateModel: fit.candidateModel ?? null,
    productionActivation: 'MANUAL ONLY: candidate fitting never changes production parameters'
  };

  await writeFile(SUMMARY_PATH, JSON.stringify(summary, null, 2) + '\n', 'utf8');
  if (fit.accepted && fit.model) {
    const moduleText = [
      '/** Generated by scripts/fit-multi-anchor-flat-disk.mjs; candidate only. */',
      'export const MULTI_ANCHOR_FLAT_DISK = Object.freeze(' +
        JSON.stringify(fit.model, null, 2) + ');',
      ''
    ].join('\n');
    await writeFile(PARAMETERS_PATH, moduleText, 'utf8');
    console.log('Accepted candidate parameters written to ' + PARAMETERS_PATH);
  } else {
    console.warn('Candidate not promoted. Production projection and measurements were not changed.');
    fit.failures.forEach(reason => console.warn('- ' + reason));
  }
  console.log(JSON.stringify(summary, null, 2));
}

main().catch(error => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
