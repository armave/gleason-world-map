test('bundled metadata checksums match the compressed country assets', async () => {
  const metadata = JSON.parse(await readFile(new URL('../data/metadata.json', import.meta.url), 'utf8'));
  for (const quality of ['low', 'medium', 'high']) {
    const bytes = await readFile(COUNTRY_DATA_FILES[quality]);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    assert.equal(sha256, metadata.boundaryDatasets[quality].sha256);
    assert.equal(bytes.length, metadata.boundaryDatasets[quality].compressedBytes);
  }
});


test('bundled Census county-equivalent labels contain complete, unique internal points', async () => {
  assert.ok(COUNTY_DATA_FILE.pathname.endsWith('/data/us-counties.json'));
  const data = JSON.parse(await readFile(COUNTY_DATA_FILE, 'utf8'));
  const metadata = JSON.parse(await readFile(new URL('../data/metadata.json', import.meta.url), 'utf8'));
  const counties = validateCountyDataset(data);
  assert.equal(data.inputSha256, metadata.sources.usCounties.extractedFileSha256);
  assert.equal(data.archiveSha256, metadata.sources.usCounties.archiveSha256);
  assert.equal(data.sourceYear, 2026);
  assert.equal(counties.length, 3222);
  assert.deepEqual(counties.find(county => county.geoid === '06037'), {
    geoid: '06037', stateCode: 'CA', name: 'Los Angeles County', lat: 34.196398, lon: -118.261862
  });
  assert.ok(counties.some(county => county.stateCode === 'AK' && county.name.endsWith('Borough')));
  assert.ok(counties.some(county => county.stateCode === 'PR' && county.name.endsWith('Municipio')));
  assert.deepEqual(counties.find(county => county.geoid === '01005'), {
    geoid: '01005', stateCode: 'AL', name: 'Barbour County', lat: 31.870069, lon: -85.400142
  });
});


test('official 2026 TIGERweb county-boundary layer is validated as GeoJSON',()=>{
  assert.ok(COUNTY_BOUNDARY_SERVICE_URL.endsWith('/tigerWMS_ACS2026/MapServer/82'));
  const geometry={type:'Polygon',coordinates:[[[0,0],[2,0],[2,2],[0,2],[0,0]]]};
  const features=Array.from({length:3001},(_,i)=>({
    type:'Feature',
    properties:{GEOID:String(i).padStart(5,'0'),STATE:'01',BASENAME:'County '+i,NAME:'County '+i,INTPTLAT:'1',INTPTLON:'1'},
    geometry
  }));
  const data=validateCountyBoundaryDataset({type:'FeatureCollection',features});
  assert.equal(data.features.length,3001);
  assert.throws(()=>validateCountyBoundaryDataset({type:'FeatureCollection',features:[...features.slice(0,-1),features[0]]}),/invalid or duplicate/);
});


test('locally bundled 2026 Census county polygons are compressed, complete and searchable', async t => {
  let bytes;
  try {
    bytes = await readFile(COUNTY_BOUNDARY_DATA_FILE);
  } catch (error) {
    if (error.code === 'ENOENT') {
      t.skip('The local Census county-boundary bundle is generated by the vendor workflow.');
      return;
    }
    throw error;
  }
  assert.ok(COUNTY_BOUNDARY_DATA_FILE.pathname.endsWith('/data/us-counties-boundaries.geojson.gz'));
  const data = JSON.parse(gunzipSync(bytes).toString('utf8'));
  const validated = validateCountyBoundaryDataset(data);
  assert.equal(data.sourceYear, 2026);
  assert.ok(validated.features.length >= 3000);
  const losAngeles = validated.features.find(feature => String(feature.properties.GEOID) === '06037');
  assert.ok(losAngeles, 'Los Angeles County polygon is bundled');
  assert.ok(Number.isFinite(Number(losAngeles.properties.INTPTLAT)));
  assert.ok(Number.isFinite(Number(losAngeles.properties.INTPTLON)));
  assert.ok(bytes.length < 90 * 1024 * 1024, 'bundle stays below GitHub large-file limit');
});
